import { createHash, createHmac, generateKeyPairSync, sign as edSign } from "node:crypto";
import { request } from "node:http";
import { connect as netConnect } from "node:net";
import { connect as tlsConnect } from "node:tls";
import { openEnvelopedData } from "./cms.mjs";
import { derivedSigner, rawOf } from "./keyhouse.mjs";
import { clientAuthority, CLIENT_CA_SHA256, keysNonce } from "./shared/binding.js";
import { CborMap, decodeCbor, CborTag } from "./shared/cbor.js";

// The AWS Nitro Enclaves platform for the keyhouse (keyhouse.mjs). Inside the enclave there is no network: the
// helper mynt-enclave-io (deploy/confidential/enclave-io) relays Unix sockets in /run/keyhouse to the parent instance
// over vsock, and answers attestation requests from the Nitro Secure Module. From here:
//
//   - attestation documents: from the module, carrying the caller's nonce, the binding of the service's keys
//     (`mynt-keys-<sha256>`, as user_data) and the service's TLS key (as public_key);
//   - AWS KMS, directly: each request signed with Signature Version 4 using the instance role's credentials (fetched
//     from the instance metadata service, through the parent) and sent over TLS, end to end, through the parent's
//     vsock-proxy. Every call carries a fresh attestation document whose public key is an RSA key made in this process,
//     as KMS's Recipient: KMS checks the document against the key policy (PCR0 must be this image's) and encrypts the
//     answer to that RSA key, so the parent, which holds the same role, can neither call KMS successfully itself (the
//     policy denies requests without a matching attestation) nor read what KMS returns;
//   - the root: generated by KMS (GenerateDataKey) and returned wrapped; unwrapped (Decrypt) only into this process;
//   - the health attester: an Ed25519 key derived from the root, because KMS signing can't be gated on attestation (a
//     KMS signing key would be usable by the parent instance's role). It exists only where the root does.
//
// Nothing here logs a credential, a document, a key or a ciphertext.

export const SOCKETS = {
  https: "/run/keyhouse/https.sock",
  kms: "/run/keyhouse/kms.sock",
  imds: "/run/keyhouse/imds.sock",
  config: "/run/keyhouse/config.sock",
  nsm: "/run/keyhouse/nsm.sock",
};
const ROOT_CONTEXT = { mynt: "keyhouse-root-v1" };
const sha256hex = (b) => createHash("sha256").update(b).digest("hex");
const hmac = (key, data) => createHmac("sha256", key).update(data).digest();

// ---- the Nitro Secure Module, through the helper ----

export function nsmClient({ socketPath = SOCKETS.nsm } = {}) {
  return {
    attest({ nonce = null, userData = null, publicKey = null }) {
      return new Promise((resolve, reject) => {
        const s = netConnect(socketPath);
        const chunks = [];
        s.on("data", (c) => chunks.push(c));
        s.on("end", () => {
          try {
            const r = JSON.parse(Buffer.concat(chunks).toString("utf8"));
            if (!r.document) return reject(new Error(`the security module answered ${r.error ?? "nothing"}`));
            resolve(Buffer.from(r.document, "base64"));
          } catch (e) {
            reject(e);
          }
        });
        s.on("error", reject);
        const b64 = (b) => (b ? Buffer.from(b).toString("base64") : "");
        s.end(`${JSON.stringify({ nonce: b64(nonce), user_data: b64(userData), public_key: b64(publicKey) })}\n`);
      });
    },
  };
}

// ---- small HTTP over a Unix socket (plain, or TLS end to end) ----

function httpOver(createConnection, { method, path, host, headers = {}, body }) {
  return new Promise((resolve, reject) => {
    const payload = body === undefined ? undefined : Buffer.from(body);
    const req = request({ method, path, host, headers: { host, ...headers, ...(payload ? { "content-length": String(payload.length) } : {}) }, createConnection, timeout: 15_000 }, (res) => {
      const chunks = [];
      res.on("data", (c) => chunks.push(c));
      res.on("end", () => resolve({ status: res.statusCode ?? 0, text: Buffer.concat(chunks).toString("utf8") }));
    });
    req.on("timeout", () => req.destroy(new Error(`${host} timed out`)));
    req.on("error", reject);
    req.end(payload);
  });
}

// ---- the instance role's credentials, from the instance metadata service (IMDSv2) ----

export function imdsCredentials({ socketPath = SOCKETS.imds, send } = {}) {
  const go = send ?? ((o) => httpOver(() => netConnect(socketPath), { host: "169.254.169.254", ...o }));
  let cached = null;
  return async () => {
    if (cached && cached.until > Date.now() + 5 * 60_000) return cached.creds;
    const t = await go({ method: "PUT", path: "/latest/api/token", headers: { "x-aws-ec2-metadata-token-ttl-seconds": "300" } });
    if (t.status !== 200) throw new Error(`the instance metadata service answered ${t.status} for a token`);
    const auth = { "x-aws-ec2-metadata-token": t.text.trim() };
    const roles = await go({ method: "GET", path: "/latest/meta-data/iam/security-credentials/", headers: auth });
    const role = roles.text.split("\n")[0]?.trim();
    if (roles.status !== 200 || !role) throw new Error("the instance has no role");
    const c = await go({ method: "GET", path: `/latest/meta-data/iam/security-credentials/${encodeURIComponent(role)}`, headers: auth });
    const j = c.status === 200 ? JSON.parse(c.text) : null;
    if (!j?.AccessKeyId || !j.SecretAccessKey) throw new Error("the instance role's credentials are unavailable");
    cached = { creds: { accessKeyId: j.AccessKeyId, secretAccessKey: j.SecretAccessKey, sessionToken: j.Token ?? null }, until: Date.parse(j.Expiration) || Date.now() + 10 * 60_000 };
    return cached.creds;
  };
}

// ---- Signature Version 4, for one POST to a JSON API ----

export function signV4({ method = "POST", host, path = "/", region, service, headers = {}, body = "", credentials, now }) {
  const amzDate = now.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}/, "");
  const day = amzDate.slice(0, 8);
  const h = { ...Object.fromEntries(Object.entries(headers).map(([k, v]) => [k.toLowerCase(), String(v)])), host, "x-amz-date": amzDate };
  if (credentials.sessionToken) h["x-amz-security-token"] = credentials.sessionToken;
  const names = Object.keys(h).sort();
  const signedHeaders = names.join(";");
  const canonical = [method, path, "", names.map((n) => `${n}:${h[n].trim().replace(/\s+/g, " ")}\n`).join(""), signedHeaders, sha256hex(body)].join("\n");
  const scope = `${day}/${region}/${service}/aws4_request`;
  const toSign = ["AWS4-HMAC-SHA256", amzDate, scope, sha256hex(canonical)].join("\n");
  const key = hmac(hmac(hmac(hmac(`AWS4${credentials.secretAccessKey}`, day), region), service), "aws4_request");
  const signature = createHmac("sha256", key).update(toSign).digest("hex");
  return { ...h, authorization: `AWS4-HMAC-SHA256 Credential=${credentials.accessKeyId}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}` };
}

// ---- KMS, attested ----

export function kmsOverSocket({ region, socketPath = SOCKETS.kms }) {
  const host = `kms.${region}.amazonaws.com`;
  // TLS to KMS itself, verified against Node's bundled roots, through the parent's vsock-proxy.
  return (headers, body) => httpOver(() => tlsConnect({ socket: netConnect(socketPath), servername: host, host, minVersion: "TLSv1.2" }), { method: "POST", path: "/", host, headers, body });
}

export function nitroKms({ region, keyArn, nsm, credentials, post, now = () => new Date() }) {
  // The Recipient key: made at boot, inside the enclave; its private half never leaves this process.
  const rsa = generateKeyPairSync("rsa", { modulusLength: 2048 });
  const spki = rsa.publicKey.export({ type: "spki", format: "der" });
  const host = `kms.${region}.amazonaws.com`;
  const call = async (target, payload) => {
    const document = await nsm.attest({ publicKey: spki });
    const body = JSON.stringify({ ...payload, KeyId: keyArn, EncryptionContext: ROOT_CONTEXT, Recipient: { KeyEncryptionAlgorithm: "RSAES_OAEP_SHA_256", AttestationDocument: document.toString("base64") } });
    const headers = signV4({ host, region, service: "kms", headers: { "content-type": "application/x-amz-json-1.1", "x-amz-target": `TrentService.${target}` }, body, credentials: await credentials(), now: now() });
    const r = await post(headers, body);
    let j = null;
    try {
      j = JSON.parse(r.text || "null");
    } catch {
      j = null;
    }
    if (r.status !== 200) throw new Error(`KMS answered ${r.status} for ${target}${typeof j?.__type === "string" ? ` (${j.__type.split("#").pop()})` : ""}`);
    if (!j?.CiphertextForRecipient || j.Plaintext) throw new Error(`KMS didn't answer ${target} for the enclave alone`);
    if (j.KeyId && j.KeyId !== keyArn) throw new Error(`KMS used another key for ${target}`);
    return { ...j, opened: openEnvelopedData(Buffer.from(j.CiphertextForRecipient, "base64"), rsa.privateKey) };
  };
  return {
    async decrypt(ciphertextBlob) {
      return (await call("Decrypt", { CiphertextBlob: ciphertextBlob })).opened;
    },
    async generateDataKey() {
      const r = await call("GenerateDataKey", { KeySpec: "AES_256" });
      return { ciphertextBlob: r.CiphertextBlob, plaintext: r.opened };
    },
  };
}

// ---- the platform ----

// The PCRs an attestation document reports, unverified: informational, for the answer's measurements. Callers verify.
function pcrsOf(document) {
  try {
    let top = decodeCbor(document);
    if (top instanceof CborTag) top = top.value;
    const body = decodeCbor(top[2]);
    const pcrs = body instanceof CborMap ? body.get("pcrs") : null;
    const hex = (i) => Buffer.from(pcrs.get(i)).toString("hex");
    return { pcr0: hex(0), pcr1: hex(1), pcr2: hex(2) };
  } catch {
    return null;
  }
}

// `clientCaSha256`: of the one authority whose client certificates the service accepts (shared/binding.js
// clientAuthority, from the same PEM the TLS server is given). It reaches the enclave from the parent instance like the
// key's ARN, so it's bound into every attestation the same way: a parent that hands the enclave an authority of its own
// (to call it as Mynt's server) changes what every verifier sees.
export function nitroPlatform({ kms, nsm, region, keyArn, clientCaSha256 }) {
  if (!CLIENT_CA_SHA256.test(clientCaSha256 ?? "")) throw new Error("the enclave needs the SHA-256 of its client-certificate authority, to bind into its attestation");
  return {
    host: "aws-nitro",
    tag: "ne",
    signingNames: ["health-attester"],
    derivedSigning: true,
    config: { kms_key: keyArn, region, client_ca_sha256: clientCaSha256 },
    async attest(nonce, keys, tlsSpki) {
      const document = await nsm.attest({ nonce: Buffer.from(nonce, "utf8"), userData: Buffer.from(keysNonce(keys), "utf8"), publicKey: tlsSpki });
      const pcrs = pcrsOf(document);
      return {
        format: "nitro-cose",
        token: document.toString("base64"),
        measurements: { host: "aws-nitro", attested: true, image_digest: null, pcrs, hardware: "aws-nitro-enclave", software: "nitro-enclave", software_version: null, debug: pcrs ? /^0+$/.test(pcrs.pcr0) : null, reason: null },
      };
    },
    async newWrappedRoot() {
      const { ciphertextBlob, plaintext } = await kms.generateDataKey();
      plaintext.fill(0);
      return ciphertextBlob;
    },
    async unwrapRoot(wrapped) {
      const root = await kms.decrypt(wrapped);
      if (root.length !== 32) throw new Error("the wrapped root isn't a 32-byte key");
      return root;
    },
    publicKey: (name, root) => rawOf(derivedSigner(name, root)),
    sign: (name, message, root) => {
      const key = derivedSigner(name, root);
      return { public_key: rawOf(key), signature: edSign(null, message, key).toString("hex") };
    },
  };
}

// ---- settings from the parent (none secret; each is bound into every attestation: the KMS key, the region, and the
// hash of the one authority whose client certificates may call) ----

const REGION = /^[a-z]{2}(-[a-z]+)+-\d{1,2}$/;
export function parseSettings(text) {
  const s = JSON.parse(text);
  if (!REGION.test(s.region ?? "")) throw new Error("settings: region isn't an AWS region name");
  const arn = new RegExp(`^arn:aws[a-z-]*:kms:${s.region}:\\d{12}:key/(mrk-[0-9a-f]{32}|[0-9a-f-]{36})$`);
  if (!arn.test(s.kms_key ?? "")) throw new Error("settings: kms_key isn't a KMS key ARN in that region");
  let authority;
  try {
    authority = clientAuthority(s.client_ca ?? "");
  } catch (e) {
    throw new Error(`settings: client_ca: ${e.message}`);
  }
  // client_ca is the certificate that was hashed, re-encoded: what the TLS server trusts is what the attestation binds.
  return { region: s.region, kms_key: s.kms_key, client_ca: authority.pem, client_ca_sha256: authority.sha256 };
}

export async function readSettings({ socketPath = SOCKETS.config, attempts = 60 } = {}) {
  for (let i = 0; ; i++) {
    try {
      const text = await new Promise((resolve, reject) => {
        const s = netConnect(socketPath);
        const chunks = [];
        s.on("data", (c) => chunks.push(c));
        s.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
        s.on("error", reject);
        s.end();
      });
      return parseSettings(text);
    } catch (e) {
      if (i + 1 >= attempts) throw e;
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
}
