export const AUDIT_ACTION_CLASSES: Readonly<Record<string, AuditClass>> = Object.freeze(
  Object.fromEntries([
    ...SECURITY.map((a) => [a, "security"]),
    ...FINANCIAL.map((a) => [a, "financial"]),
    ...OBLIGATIONS.map((a) => [a, "obligations"]),
    ...WORKSPACE.map((a) => [a, "workspace"]),
  ]),
);

// Actions the source builds from a template, as the source writes them; each expansion is listed above.
export const AUDIT_ACTION_TEMPLATES = ["${op}_refused", "app_${kind}", "review_${r.kind}", "admin_${action}"] as const;

export const auditClass = (action: string): AuditClass => AUDIT_ACTION_CLASSES[action] ?? "workspace";

// Each class's actions, for filtering in SQL; "workspace" also takes every action in no list.
export const actionsOfClass = (c: AuditClass) => Object.entries(AUDIT_ACTION_CLASSES).filter(([, k]) => k === c).map(([a]) => a);
export const classifiedActions = () => Object.keys(AUDIT_ACTION_CLASSES);

// The lists themselves, for the test that every action is in exactly one.
export const AUDIT_CLASS_LISTS: Readonly<Record<AuditClass, readonly string[]>> = { security: SECURITY, obligations: OBLIGATIONS, financial: FINANCIAL, workspace: WORKSPACE };
