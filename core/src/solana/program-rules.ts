// Comments become spaces (lines keep their numbers); strings and chars stay, since pubkey!("...") is a string.
export function stripComments(src: string): string {
  let out = "";
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    const d = src[i + 1];
    if (c === "/" && d === "/") {
      while (i < n && src[i] !== "\n") (out += " "), i++;
      continue;
    }
    if (c === "/" && d === "*") {
      let depth = 0;
      while (i < n) {
        if (src[i] === "/" && src[i + 1] === "*") {
          depth++;
          out += "  ";
          i += 2;
        } else if (src[i] === "*" && src[i + 1] === "/") {
          depth--;
          out += "  ";
          i += 2;
          if (depth === 0) break;
        } else {
          out += src[i] === "\n" ? "\n" : " ";
          i++;
        }
      }
      continue;
    }
    // Raw strings r"..." / r#"..."#
    const raw = /^r(#*)"/.exec(src.slice(i, i + 10));
    if (raw && !/[A-Za-z0-9_]/.test(src[i - 1] ?? "")) {
      const close = `"${raw[1]}`;
      const end = src.indexOf(close, i + raw[0].length);
      const stop = end < 0 ? n : end + close.length;
      out += src.slice(i, stop);
      i = stop;
      continue;
    }
    if (c === '"') {
      let j = i + 1;
      while (j < n && src[j] !== '"') j += src[j] === "\\" ? 2 : 1;
      out += src.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

const lineOf = (text: string, index: number) => text.slice(0, index).split("\n").length;
// The text from `open` (an opening bracket) to its matching close, exclusive; brackets inside strings ignored.
function balanced(text: string, open: number): { body: string; end: number } | null {
  const pairs: Record<string, string> = { "{": "}", "(": ")", "[": "]" };
  const o = text[open];
  const close = pairs[o];
  if (!close) return null;
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    const ch = text[i];
    if (ch === '"') {
      i++;
      while (i < text.length && text[i] !== '"') i += text[i] === "\\" ? 2 : 1;
      continue;
    }
    if (ch === o) depth++;
    else if (ch === close && --depth === 0) return { body: text.slice(open + 1, i), end: i };
  }
  return null;
}

interface AccountsField {
  name: string;
  type: string;
  attrs: string;
  line: number;
}
interface AccountsStruct {
  name: string;
  file: string;
  fields: AccountsField[];
}

// #[derive(Accounts)] structs: each field with its type and its #[account(...)] attributes.
function accountsStructs(file: string, code: string): AccountsStruct[] {
  const out: AccountsStruct[] = [];
  const re = /#\[derive\([^\]]*\bAccounts\b[^\]]*\)\][\s\S]*?\bstruct\s+(\w+)\s*(?:<[^>{]*>)?\s*\{/g;
  for (let m; (m = re.exec(code)); ) {
    const brace = m.index + m[0].length - 1;
    const b = balanced(code, brace);
    if (!b) continue;
    const fields: AccountsField[] = [];
    let attrs = "";
    let i = 0;
    const body = b.body;
    while (i < body.length) {
      const rest = body.slice(i);
      const attr = /^\s*#\s*\[/.exec(rest);
      if (attr) {
        const start = i + attr[0].length - 1;
        const a = balanced(body, start);
        if (!a) break;
        attrs += ` ${a.body}`;
        i = a.end + 1;
        continue;
      }
      const field = /^\s*(?:pub(?:\([^)]*\))?\s+)?(\w+)\s*:\s*/.exec(rest);
      if (!field) {
        i++;
        continue;
      }
      // The type runs to the next comma at depth 0 (generics hold commas).
      let j = i + field[0].length;
      let depth = 0;
      for (; j < body.length; j++) {
        const ch = body[j];
        if (ch === "<" || ch === "(" || ch === "[") depth++;
        else if (ch === ">" || ch === ")" || ch === "]") depth--;
        else if (ch === "," && depth === 0) break;
      }
      fields.push({ name: field[1], type: body.slice(i + field[0].length, j).trim(), attrs, line: lineOf(code, brace + 1 + i + field[0].length) });
      attrs = "";
      i = j + 1;
    }
    out.push({ name: m[1], file, fields });
  }
  return out;
}

const isSignerField = (f: AccountsField | undefined) => !!f && (/^Signer\s*</.test(f.type) || /(^|[\s,(])signer(\s*[,)@]|\s*$)/.test(f.attrs));

interface Handler {
  name: string;
  accounts: string;
  params: string[];
  body: string;
  bodyStart: number;
  file: string;
}

// Functions that take a `Context<X>`: instruction handlers, in the #[program] module or in modules it calls.
function handlers(file: string, code: string): Handler[] {
  const out: Handler[] = [];
  const re = /\bfn\s+(\w+)\s*(?:<[^>(]*>)?\s*\(/g;
  for (let m; (m = re.exec(code)); ) {
    const p = balanced(code, m.index + m[0].length - 1);
    if (!p) continue;
    const ctx = /\bContext\s*<\s*(?:'\w+\s*,\s*)*(\w+)/.exec(p.body);
    if (!ctx) continue;
    const params = [...p.body.matchAll(/(?:^|,)\s*(?:mut\s+)?(\w+)\s*:/g)].map((x) => x[1]).filter((x) => x !== "ctx");
    const brace = code.indexOf("{", p.end);
    const b = brace >= 0 ? balanced(code, brace) : null;
    if (!b) continue;
    out.push({ name: m[1], accounts: ctx[1], params, body: b.body, bodyStart: brace + 1, file });
  }
  return out;
}

const PUBKEY_LITERAL = /(?:\bpubkey!\s*\(\s*"([1-9A-HJ-NP-Za-km-z]{32,44})"\s*\)|\bPubkey::from_str\s*\(\s*"([1-9A-HJ-NP-Za-km-z]{32,44})"\s*\)|\bPubkey::from_str_const\s*\(\s*"([1-9A-HJ-NP-Za-km-z]{32,44})"\s*\)|\bPubkey::new_from_array\s*\(\s*\[([0-9,\s_u8x]+)\]\s*\))/;

interface HardKey {
  name: string | null; // the constant's name, or null for a literal written in place
  address: string;
  file: string;
  line: number;
}

function literalAddress(m: RegExpExecArray): string | null {
  const s = m[1] ?? m[2] ?? m[3];
  if (s) return isAddress(s) ? s : null;
  if (m[4]) {
    const bytes = m[4].split(",").map((x) => x.trim().replace(/u8$/, "").replace(/_/g, "")).filter(Boolean).map((x) => Number(x));
    return bytes.length === 32 && bytes.every((x) => Number.isInteger(x) && x >= 0 && x < 256) ? base58Encode(Uint8Array.from(bytes)) : null;
  }
  return null;
}

function hardKeys(file: string, code: string): HardKey[] {
  const keys: HardKey[] = [];
  const decl = new RegExp(String.raw`\b(?:const|static)\s+(\w+)\s*:\s*(?:[\w:]+::)?Pubkey\s*=\s*` + PUBKEY_LITERAL.source, "g");
  for (let m; (m = decl.exec(code)); ) {
    const address = literalAddress({ ...m, 1: m[2], 2: m[3], 3: m[4], 4: m[5] } as unknown as RegExpExecArray);
    if (address) keys.push({ name: m[1], address, file, line: lineOf(code, m.index) });
  }
  // `pub mod admin { declare_id!("...") }` and `declare_id!` outside the crate root also define a key; only the
  // crate root's is the program's own address (excluded by the caller).
  return keys;
}

