// What a detection reports, before the entry it belongs to is attached.
interface Hit {
  file?: string;
  line?: number;
  detail: string;
  allowed?: boolean; // found, but allowed (Mynt's own signer as a pinned admin): noted, never blocking
}


// Everything the source detections share: the code with comments stripped, the accounts structs, the handlers,
// the #[account] state structs and the hard-coded keys.
class SourceIndex {
  readonly tree: CrateTree;
  readonly code: Map<string, string>;
  readonly structs: AccountsStruct[];
  readonly byName: Map<string, AccountsStruct>;
  readonly state: Map<string, { fields: { name: string; type: string; attrs: string }[]; file: string; line: number }>;
  readonly handlers: (Handler & { text: string })[];
  readonly named: Map<string, HardKey>;
  constructor(
    readonly all: Record<string, string>,
    readonly programId: string,
    compiled: string[] | null = null,
  ) {
    // Every file the compiler read (dep-info) when Mynt has that; otherwise every file reachable from a crate root
    // (mod, #[path], include!), wherever it lives. Nothing else.
    this.tree = resolveCrateTree(all);
    this.code = compiled
      ? new Map(compiled.filter((p) => all[p] !== undefined).map((p) => [p, stripComments(all[p])]))
      : new Map([...this.tree.code].map(([p, t]) => [p, stripComments(t)]));
    this.structs = [...this.code].flatMap(([file, text]) => accountsStructs(file, text));
    this.byName = new Map(this.structs.map((s) => [s.name, s]));
    this.handlers = [...this.code].flatMap(([file, text]) => handlers(file, text).map((h) => ({ ...h, text })));
    this.named = new Map(
      [...this.code]
        .flatMap(([file, text]) => hardKeys(file, text))
        .filter((k) => k.address !== programId && !WELL_KNOWN.has(k.address))
        .map((k) => [k.name!, k]),
    );
    this.state = new Map();
    for (const [file, text] of this.code) {
      const re = /#\[account(?:\([^)]*\))?\]\s*(?:#\[[^\]]*\]\s*)*pub\s+struct\s+(\w+)\s*\{/g;
      for (let m; (m = re.exec(text)); ) {
        const b = balanced(text, m.index + m[0].length - 1);
        if (!b) continue;
        const fields: { name: string; type: string; attrs: string }[] = [];
        let attrs = "";
        for (const line of b.body.split("\n")) {
          const a = /#\[([^\]]*)\]/.exec(line);
          if (a) attrs += ` ${a[1]}`;
          const f = /^\s*pub\s+(\w+)\s*:\s*([^,]+),?/.exec(line);
          if (f) {
            fields.push({ name: f[1], type: f[2].trim(), attrs });
            attrs = "";
          }
        }
        this.state.set(m[1], { fields, file, line: lineOf(text, m.index) });
      }
    }
  }
  lineAt(text: string, i: number) {
    return lineOf(text, i);
  }
  authz(expr: string): { key: HardKey | null; address: string } | null {
    const lit = PUBKEY_LITERAL.exec(expr);
    if (lit) {
      const a = literalAddress(lit);
      if (a && a !== this.programId && !WELL_KNOWN.has(a)) return { key: null, address: a };
    }
    for (const [n, k] of this.named) if (new RegExp(String.raw`(^|[^\w])(?:[\w:]+::)?${n}\b`).test(expr)) return { key: k, address: k.address };
    return null;
  }
}

